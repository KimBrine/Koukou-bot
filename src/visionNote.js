/**
 * 图片消息的处理分工：**视觉模型只读图，文字模型写回复。**
 *
 * 踩过的坑（2026-09-23 22:20，群 1124442491，群友 714qc 发了张聊天记录截图）：
 * 以前是把「人设提示词 + 聊天历史 + 图片」一起丢给视觉模型（qwen3.7-flash），让它**直接写群聊回复**。
 * 结果它看到聊天记录截图就切进了"图片分析"模式，回了整整一篇：
 *   「这是一段非常典型的**大学生QQ群（极大概率是大学班级群…以下是对这段聊天记录及最后图片的详细解读：
 *     ### 1. 核心事件：…」
 * 而人设提示词里明明写着"看到群友发的图就像真人刷到那样随口回一句，绝对不要写图片分析/总结"——
 * 问题是它整条**回复本身就是**分析报告，那条规则根本没机会生效。
 *
 * 现在的分工：
 *   1. 视觉模型 describeImages() 只做读图，输出平实的一句描述（短、无文体，见 VISION_DESCRIBE_PROMPT）；
 *   2. 描述当作**内部备注**拼进系统提示词，由文字模型（deepseek-flash）照常写人设回复。
 * 好处：读图稳定（这是视觉模型擅长的），人设和形态规则也守得住（文字模型一向守得住）。
 */

