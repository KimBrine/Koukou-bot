export function isQuestionMode(text, { isPrivate = false, atBot = false } = {}) {
  return (isPrivate || atBot) && /(^|[\s，。！？；：、（(【\p{Script=Han}])\/Q(?![A-Za-z_])/iu.test(String(text || ''))
}

